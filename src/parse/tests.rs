//! The parser corpus. Every row is `(input, expected)`; the clock is fixed to Wednesday 2026-11-25 14:00:00.
//!
//! `D(secs, label)`: a length. `A("YYYY-MM-DD HH:MM", label)`: a clock time. `F(error)`: must not parse.

use super::*;
use chrono::NaiveDate;

#[derive(Debug)]
enum E {
    D(i64, &'static str),
    A(&'static str, &'static str),
    F(Error),
}
use E::{A, D, F};

fn now() -> NaiveDateTime {
    NaiveDate::from_ymd_opt(2026, 11, 25).unwrap().and_hms_opt(14, 0, 0).unwrap()
}

fn check(table: &[(&str, E)], fallback: Lang) {
    let mut bad = Vec::new();
    for (input, exp) in table {
        let got = parse(input, now(), fallback);
        let ok = match (&got, exp) {
            (Ok(p), D(secs, label)) => !p.absolute && p.secs == *secs && p.label == *label,
            (Ok(p), A(at, label)) => p.absolute && p.fire_at.format("%Y-%m-%d %H:%M").to_string() == *at && p.label == *label,
            (Err(e), F(want)) => e == want,
            _ => false,
        };
        if !ok {
            bad.push(format!("{input:?}: expected {exp:?}, got {:?}", got.map(|p| (p.secs, p.fire_at.to_string(), p.label, p.absolute))));
        }
    }
    assert!(bad.is_empty(), "{} of {} cases failed:\n{}", bad.len(), table.len(), bad.join("\n"));
}

