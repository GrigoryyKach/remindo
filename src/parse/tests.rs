#[test]
fn clamps_to_seven_days() {
    for (input, secs) in [
        ("in 8 days", MAX_SECS),
        ("in 10 days", MAX_SECS),
        ("in 2 weeks", MAX_SECS),
        ("in a month", MAX_SECS),
        ("через 2 недели", MAX_SECS),
        ("через месяц", MAX_SECS),
        ("через 200 часов", MAX_SECS),
        ("in 100000 minutes", MAX_SECS),
        ("in 99999999 minutes", MAX_SECS),
        ("через 4000000 часов", MAX_SECS),
    ] {
        let p = parse(input, now(), Lang::En).unwrap_or_else(|e| panic!("{input}: {e:?}"));
        assert_eq!(p.secs, secs, "{input}");
        assert!(p.notes.contains(&Note::ClampedMax), "{input}");
    }
    // Exactly seven days is not clamped, and 100 hours is fine.
    assert!(parse("in 7 days", now(), Lang::En).unwrap().notes.is_empty());
    assert_eq!(parse("через 100 часов", now(), Lang::Ru).unwrap().secs, 360_000);
}

#[test]
fn clock_in_the_past_means_tomorrow() {
    for input in ["at 6", "в 6 утра", "at 14:00", "at 9 am", "today at 8 am", "в полночь", "6:00"] {
        let p = parse(input, now(), Lang::En).unwrap();
        assert!(p.notes.contains(&Note::Tomorrow), "{input}");
        assert!(p.next_day, "{input}");
        assert!(p.fire_at > now(), "{input}");
    }
    for input in ["at 15", "в 18:30", "tomorrow at 6", "завтра в 9", "в пятницу в 10"] {
        let p = parse(input, now(), Lang::En).unwrap();
        assert!(!p.notes.contains(&Note::Tomorrow), "{input}");
    }
}

#[test]
fn two_time_phrases_warn_and_use_the_first() {
    let p = parse("через 5 минут позвонить через 10 минут", now(), Lang::Ru).unwrap();
    assert_eq!(p.secs, 300);
    assert_eq!(p.label, "позвонить через 10 минут");
    assert_eq!(p.notes, vec![Note::IgnoredSecond("через 10 минут".into())]);

    let p = parse("in 5 min call Bob in 10 min", now(), Lang::En).unwrap();
    assert_eq!(p.secs, 300);
    assert!(matches!(p.notes.as_slice(), [Note::IgnoredSecond(_)]));

    let p = parse("15м плита 20м", now(), Lang::Ru).unwrap();
    assert_eq!(p.secs, 900);
    assert!(matches!(p.notes.as_slice(), [Note::IgnoredSecond(_)]));

    let p = parse("в 18:30 через 10 минут", now(), Lang::Ru).unwrap();
    assert!(p.absolute);
    assert!(matches!(p.notes.as_slice(), [Note::IgnoredSecond(_)]));

    // A weaker phrase in the label is not an ambiguity.
    let p = parse("купить 2 м ткани через 10 минут", now(), Lang::Ru).unwrap();
    assert!(p.notes.is_empty());
    let p = parse("позвонить в 5 магазинов через 10 минут", now(), Lang::Ru).unwrap();
    assert_eq!(p.secs, 600);
    assert!(p.notes.is_empty());
}

#[test]
fn default_label_follows_the_language_of_the_text() {
    let p = parse("15 min", now(), Lang::Ru).unwrap();
    assert_eq!((p.lang, p.label_or_default().as_str()), (Lang::En, "Timer"));
    let p = parse("через 15 минут", now(), Lang::En).unwrap();
    assert_eq!((p.lang, p.label_or_default().as_str()), (Lang::Ru, "Таймер"));
    let p = parse("через 15 хвилин", now(), Lang::En).unwrap();
    assert_eq!((p.lang, p.label_or_default().as_str()), (Lang::Uk, "Таймер"));
    // Nothing in the text says which language: the interface language decides.
    let p = parse("15m", now(), Lang::Uk).unwrap();
    assert_eq!((p.lang, p.label_or_default().as_str()), (Lang::Uk, "Таймер"));
    let p = parse("15m", now(), Lang::En).unwrap();
    assert_eq!(p.label_or_default(), "Timer");
    // A typed label wins.
    let p = parse("15m Tea", now(), Lang::En).unwrap();
    assert_eq!(p.label_or_default(), "Tea");
}

