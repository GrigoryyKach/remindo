#[test]
fn never_panics_and_stays_in_range() {
    // A deterministic soup of the pieces the parser knows, mixed with noise.
    let pieces = [
        "через", "in", "at", "в", "о", "за", "15", "1", "0", "7", "24", "60", "100", "2.5", "2,5", "1:15", "18:30", "0:01:30", "мин", "min", "m", "м", "ч", "h", "с", "s", "d", "д",
        "час", "часа", "hour", "минут", "хвилин", "годин", "pm", "am", "утра", "вечера", "ночи", "дня", "завтра", "tomorrow", "понедельник", "mon", "пятницу", "half", "полчаса", "пол", "часа", "полтора",
        "an", "a", "and", "и", "і", "of", "quarter", "четверть", "с", "половиной", "пару", "couple", "-", "—", ",", ":", ".", "!", "'", "ё", "п'ять", "двадцать", "five", "twenty", "плита", "tea", "😀", "💥",
        "٣", "999999999999", "00", "::", "1:", ":5", "a.m.", "p.m.", "o'clock", "полдень", "noon", "remind", "me", "напомни", "нагадай", "to", "что",
    ];
    let mut seed: u64 = 0x9E37_79B9_7F4A_7C15;
    let mut next = || {
        seed ^= seed << 13;
        seed ^= seed >> 7;
        seed ^= seed << 17;
        seed
    };
    for _ in 0..30_000 {
        let n = (next() % 9) as usize;
        let mut s = String::new();
        for k in 0..n {
            if k > 0 && next() % 4 != 0 {
                s.push(' ');
            }
            s.push_str(pieces[(next() % pieces.len() as u64) as usize]);
        }
        if let Ok(p) = parse(&s, now(), Lang::En) {
            assert!(p.secs >= 1 && p.secs <= MAX_SECS, "{s:?} -> {}", p.secs);
            assert!(p.fire_at > now(), "{s:?}");
        }
    }
}

